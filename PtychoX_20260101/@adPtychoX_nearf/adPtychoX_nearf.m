                                                wavefront2, ...
                                                memo1, ...
                                                H_d2, ...
                                                shiftsPos, ...
                                                foo.mag...
                                               );

            % dldw1 = conj(dldw1);
            % dldw2 = conj(dldw2);
        end
    end
end